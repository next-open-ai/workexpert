const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('workexpertDesktop', {
  pickFile: () => ipcRenderer.invoke('workexpert:pick-file'),
  pickProjectDirectory: () => ipcRenderer.invoke('workexpert:pick-project-directory'),
  createProjectWorkspace: (value) => ipcRenderer.invoke('workexpert:create-project-workspace', value),
  listProjectFiles: (root) => ipcRenderer.invoke('workexpert:list-project-files', root),
  readProjectFile: (root, relative) => ipcRenderer.invoke('workexpert:read-project-file', root, relative),
  writeProjectFile: (root, relative, content) => ipcRenderer.invoke('workexpert:write-project-file', root, relative, content),
  syncProjectWorkspace: (root, runId) => ipcRenderer.invoke('workexpert:sync-project-workspace', root, runId),
  materializeProjectAssets: (root, assetIds) => ipcRenderer.invoke('workexpert:materialize-project-assets', root, assetIds),
  registerPreviewRoot: (root) => ipcRenderer.invoke('workexpert:register-preview-root', root),
  registerAssetPreviewRoot: (assetId) => ipcRenderer.invoke('workexpert:register-asset-preview-root', assetId),
  readProjectPreview: (root, relative) => ipcRenderer.invoke('workexpert:read-project-preview', root, relative),
  readAssetPreview: (assetId) => ipcRenderer.invoke('workexpert:read-asset-preview', assetId),
  revealProjectFile: (root, relative) => ipcRenderer.invoke('workexpert:reveal-project-file', root, relative),
  openAssetInBrowser: (assetId) => ipcRenderer.invoke('workexpert:open-asset-in-browser', assetId),
  openProjectFileInBrowser: (root, relative) => ipcRenderer.invoke('workexpert:open-project-file-in-browser', root, relative),
  pickSkill: () => ipcRenderer.invoke('workexpert:pick-skill'),
  createSkill: (skill) => ipcRenderer.invoke('workexpert:create-skill', skill),
  writeSkillDraft: (draft) => ipcRenderer.invoke('workexpert:write-skill-draft', draft),
  readSkillDraft: (path) => ipcRenderer.invoke('workexpert:read-skill-draft', path),
  listSkillFiles: (path) => ipcRenderer.invoke('workexpert:list-skill-files', path),
  readSkillFile: (path) => ipcRenderer.invoke('workexpert:read-skill-file', path),
  writeSkillFile: (path, content) => ipcRenderer.invoke('workexpert:write-skill-file', path, content),
  deleteManagedSkill: (path) => ipcRenderer.invoke('workexpert:delete-managed-skill', path),
  installSkill: (reference) => ipcRenderer.invoke('workexpert:install-skill', reference),
  importGitSkill: (url) => ipcRenderer.invoke('workexpert:import-git-skill', url),
  findSkills: (query, batchCount) => ipcRenderer.invoke('workexpert:find-skills', query, batchCount),
  openExternal: (url) => ipcRenderer.invoke('workexpert:open-external', url),
  getModelConfig: () => ipcRenderer.invoke('workexpert:get-model-config'),
  saveModelConfig: (config) => ipcRenderer.invoke('workexpert:save-model-config', config),
  getSearchConfig: () => ipcRenderer.invoke('workexpert:get-search-config'),
  saveSearchConfig: (config) => ipcRenderer.invoke('workexpert:save-search-config', config),
  testProvider: (value) => ipcRenderer.invoke('workexpert:test-provider', value),
  listProviderModels: (value) => ipcRenderer.invoke('workexpert:list-provider-models', value),
  listOllamaModels: (baseUrl) => ipcRenderer.invoke('workexpert:list-ollama-models', baseUrl),
  pullOllamaModel: (baseUrl, modelName) => ipcRenderer.invoke('workexpert:pull-ollama-model', baseUrl, modelName),
  storageGet: (key) => ipcRenderer.invoke('workexpert:storage-get', key),
  storageSet: (key, value) => ipcRenderer.invoke('workexpert:storage-set', key, value),
  listAssets: () => ipcRenderer.invoke('workexpert:list-assets'),
  archiveArtifact: (artifact) => ipcRenderer.invoke('workexpert:archive-artifact', artifact),
  linkAssetsToProject: (value) => ipcRenderer.invoke('workexpert:link-assets-to-project', value),
  unlinkAssetsFromProject: (assetIds) => ipcRenderer.invoke('workexpert:unlink-assets-from-project', assetIds),
  deleteAssets: (assetIds) => ipcRenderer.invoke('workexpert:delete-assets', assetIds),
  saveAsset: (assetId) => ipcRenderer.invoke('workexpert:save-asset', assetId),
  revealAsset: (assetId) => ipcRenderer.invoke('workexpert:reveal-asset', assetId),
  getChannelSettings: () => ipcRenderer.invoke('workexpert:get-channel-settings'),
  saveChannelSettings: (payload) => ipcRenderer.invoke('workexpert:save-channel-settings', payload),
  gatewayStatus: () => ipcRenderer.invoke('workexpert:gateway-status'),
  gatewayRestart: () => ipcRenderer.invoke('workexpert:gateway-restart'),
  getLocalEmbeddingStatus: () => ipcRenderer.invoke('workexpert:get-local-embedding-status'),
  getLocalEmbeddingSettings: () => ipcRenderer.invoke('workexpert:get-local-embedding-settings'),
  saveLocalEmbeddingSettings: (value) => ipcRenderer.invoke('workexpert:save-local-embedding-settings', value),
  setLocalEmbeddingEnabled: (enabled) => ipcRenderer.invoke('workexpert:set-local-embedding-enabled', enabled),
  restartLocalEmbedding: () => ipcRenderer.invoke('workexpert:restart-local-embedding'),
  checkEnvironment: () => ipcRenderer.invoke('workexpert:env-check'),
  onEnvCheckProgress: (callback) => {
    const listener = (_event, payload) => callback(payload);
    ipcRenderer.on('workexpert:env-check-progress', listener);
    return () => ipcRenderer.removeListener('workexpert:env-check-progress', listener);
  },
});
